// Проверка отбора фрагментов и чистки ссылок. Запуск: node сайт/помощник/test.mjs
import { pick, fixRefs, docHint } from "./worker.js";

let fails = 0;
function check(name, cond, detail) {
  if (cond) { console.log("  OK   " + name); return }
  fails++;
  console.log("  СБОЙ " + name + (detail ? "  → " + detail : ""));
}
function top(q, prev) {
  const r = pick(q, prev || "");
  return r.length ? r[0] : null;
}

console.log("=== Отбор фрагментов ===");
const cases = [
  ["какое нарушение за ненормативную лексику", "КоАП ст. 5.4"],
  ["меня обозвали матом на посту", "КоАП ст. 5.4"],
  ["что будет за угон военной машины", "УК ст. 67"],
  ["опоздал на построение что грозит", "ДУ ст. 10"],
  ["что такое статья 37 УКПС", "УКПС ст. 37"],
  ["статья 105 УК это что", "УК ст. 105"],
];
for (const [q, want] of cases) {
  const t = top(q);
  check(`«${q}» → ${want}`, t && t.r === want, t ? t.r + " — " + t.t.slice(0, 40) : "ничего не найдено");
}

console.log("\n=== Вопрос не про наши документы ===");
for (const q of ["как приготовить борщ", "погода в Москве завтра", "кто выиграл чемпионат"]) {
  check(`«${q}» отсеян`, pick(q, "").length === 0);
}

console.log("\n=== Уточняющий вопрос помнит предыдущий ===");
const alone = top("а после этого что делать?");
const withPrev = top("а после этого что делать?", "задержал нарушителя на КПП");
check("без контекста ничего не находит", alone === null);
check("с контекстом находит норму", withPrev !== null, withPrev ? withPrev.r : "пусто");

console.log("\n=== Подсказка документа ===");
check("«по УКПС» → УКПС", docHint("что говорит УКПС про посты") === "УКПС");
check("«дисциплинарный» → ДУ", docHint("что в дисциплинарном уставе") === "ДУ");
check("«коап» → КоАП", docHint("а в КоАП что") === "КоАП");
check("обычный вопрос → null", docHint("напали на посту") === null);

console.log("\n=== Чистка выдуманных ссылок ===");
const allowed = ["УКПС ст. 30", "ДУ ст. 10", "ВУ ст. 5.3"];
const a1 = fixRefs("Вывод.\n1. Шаг\nОснование: УКПС ст. 30, ДУ ст. 99, КоАП ст. 5.4", allowed);
check("выдуманные статьи убраны", a1.endsWith("Основание: УКПС ст. 30"), a1.split("\n").pop());
const a2 = fixRefs("Вывод.\nОснование: ВУ ст. 1.10, ДУ ст. 3", allowed);
check("строка убрана целиком, если всё выдумано", !a2.includes("Основание"), a2);
const a3 = fixRefs("Вывод.\nОснование: ст. 30 УКПС", allowed);
check("обратный порядок «ст. 30 УКПС» распознан", a3.includes("Основание: УКПС ст. 30"), a3);
const a4 = fixRefs("Вывод без оснований.\n1. Шаг", allowed);
check("ответ без строки основания не ломается", a4 === "Вывод без оснований.\n1. Шаг");

console.log(fails ? `\nПРОВАЛЕНО: ${fails}` : "\nВсе проверки пройдены");
process.exit(fails ? 1 : 0);
