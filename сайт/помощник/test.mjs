// Проверка отбора фрагментов и чистки ссылок. Запуск: node сайт/помощник/test.mjs
import { pick, fixRefs, docHint } from "./worker.js";

let fails = 0;
function check(name, cond, detail) {
  if (cond) { console.log("  OK   " + name); return }
  fails++;
  console.log("  СБОЙ " + name + (detail ? "  → " + detail : ""));
}
function top(q, prev) {
  const r = pick(q, prev || "");
  return r.length ? r[0] : null;
}

console.log("=== Отбор фрагментов ===");
const cases = [
  ["какое нарушение за ненормативную лексику", "КоАП ст. 5.4"],
  ["меня обозвали матом на посту", "КоАП ст. 5.4"],
  ["что будет за угон военной машины", "УК ст. 67"],
  ["опоздал на построение что грозит", "ДУ ст. 10"],
  ["что такое статья 37 УКПС", "УКПС ст. 37"],
  ["статья 105 УК это что", "УК ст. 105"],
];
for (const [q, want] of cases) {
  const t = top(q);
  check(`«${q}» → ${want}`, t && t.r === want, t ? t.r + " — " + t.t.slice(0, 40) : "ничего не найдено");
}

// вопросы, на которых помощник реально отказал курсанту 18.09.2026 — в топ-8 должна быть нужная норма
